export async function askHeroMentor(query: string): Promise<string> {
  const trimmed = query.trim().toLowerCase();

  // Try Gemini API if key is available
  const apiKey = (typeof process !== 'undefined' && process.env?.GEMINI_API_KEY) || (import.meta as unknown as { env: Record<string, string> }).env?.VITE_GEMINI_API_KEY;

  if (apiKey) {
    try {
      const ai = new GoogleGenAI({ apiKey });
      const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: query,
        config: {
          systemInstruction: 'คุณคือ "พี่ฮีโร่ที่ปรึกษา" (Drug-Free Hero Mentor) เป็นรุ่นพี่นักเรียนฮีโร่ผู้ใจดี สดใส ให้กำลังใจวัยรุ่นมัธยมศึกษา ให้ความรู้เรื่องพิษภัยยาเสพติด บุหรี่ไฟฟ้า วิธีปฏิเสธเพื่อนเมื่อถูกชวน และการรับมือความเครียด ตอบภาษาไทยด้วยน้ำเสียงเป็นมิตร สร้างแรงบันดาลใจ สั้นกระชับ เข้าใจง่าย 3-4 บรรทัด และแนะนำสายด่วน 1165 หรือ 1386 เสมอเมื่อเกี่ยวข้อง',
        }
      });
      if (response.text) {
        return response.text;
      }
    } catch {
      // Fallback below
    }
  }

  // Smart Offline Knowledge Matcher
  for (const [key, answer] of Object.entries(OFFLINE_KNOWLEDGE)) {
    if (trimmed.includes(key)) {
      return answer;
    }
  }

  return 'พี่ฮีโร่ขอเป็นกำลังใจให้น้องเสมอครับ! ทุกปัญหามีทางออกที่ดีและปลอดภัยเสมอ ไม่ว่าจะเป็นเรื่องเรียน เรื่องเพื่อน หรือความเครียด ปรึกษาครูแนะแนว พ่อแม่ หรือโทรสายด่วนสุขภาพจิต 1323 (โทรฟรี 24 ชม.) และหากต้องการความรู้หรือคำแนะนำเรื่องยาเสพติด โทร 1165 ได้เลยครับ!';
}
